#!/usr/bin/env node
/**
 * Static site build for the World Students platform (no dependencies, Node 18+).
 *
 *   src/pages/*.html      page content + front matter (JSON in a leading HTML comment)
 *   src/partials/*.html   shared markup (preloader, topbar, brand, account button, display prefs, footer brand)
 *   src/data/menu.json    header mega menu, mobile accordion and footer columns (single source of truth)
 *   src/data/site.json    site-wide settings (domain, name, fonts, shared scripts)
 *   src/styles/*.css      stylesheet modules, concatenated in file-name order -> assets/css/style.css
 *   src/scripts/main/*.js main.js modules, concatenated in file-name order -> assets/js/main.js
 *   src/scripts/*.js      standalone scripts -> assets/js/
 *   public/               copied to the output as is (images, documents, api/, robots.txt, manifest)
 *
 * Output: dist/ (upload its contents to public_html). Asset URLs get a content hash (?v=xxxxxxxx),
 * so browsers never keep a stale CSS/JS after a deploy. sitemap.xml is generated from indexable pages.
 *
 * Usage: node tools/build.mjs [--out dist]
 */
import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const SRC = path.join(ROOT, 'src')
const outArg = process.argv.indexOf('--out')
const OUT = path.resolve(ROOT, outArg > 0 ? process.argv[outArg + 1] : 'dist')

const read = p => fs.readFileSync(p, 'utf8')
const write = (p, s) => { fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, s) }
const hash = s => crypto.createHash('sha256').update(s).digest('hex').slice(0, 10)
const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#x27;')
const listDir = (d, ext) => fs.existsSync(d) ? fs.readdirSync(d).filter(f => f.endsWith(ext)).sort() : []

const site = JSON.parse(read(path.join(SRC, 'data/site.json')))
const menu = JSON.parse(read(path.join(SRC, 'data/menu.json'))).groups
const partial = name => read(path.join(SRC, 'partials', name + '.html')).replace(/\s+$/, '')

/* ---------------------------------------------------------------- clean output */
fs.rmSync(OUT, { recursive: true, force: true })
fs.mkdirSync(OUT, { recursive: true })

/* ---------------------------------------------------------------- public/ */
function copyDir(from, to) {
	for (const e of fs.readdirSync(from, { withFileTypes: true })) {
		const a = path.join(from, e.name), b = path.join(to, e.name)
		if (e.isDirectory()) copyDir(a, b)
		else { fs.mkdirSync(to, { recursive: true }); fs.copyFileSync(a, b) }
	}
}
copyDir(path.join(ROOT, 'public'), OUT)

/* ---------------------------------------------------------------- assets */
const assetVersion = {}
function emitAsset(rel, content) {
	write(path.join(OUT, rel), content)
	assetVersion[rel] = hash(content)
}
const banner = what => '/* Generated by tools/build.mjs from ' + what + ' - edit the sources, not this file. */\n'
emitAsset('assets/css/style.css', banner('src/styles/*.css') + listDir(path.join(SRC, 'styles'), '.css')
	.map(f => '/* ---- ' + f + ' ---- */\n' + read(path.join(SRC, 'styles', f)).replace(/\s+$/, '')).join('\n\n') + '\n')
emitAsset('assets/js/main.js', banner('src/scripts/main/*.js') + listDir(path.join(SRC, 'scripts/main'), '.js')
	.map(f => '/* ---- ' + f + ' ---- */\n' + read(path.join(SRC, 'scripts/main', f)).replace(/\s+$/, '')).join('\n\n') + '\n')
for (const f of listDir(path.join(SRC, 'scripts'), '.js')) emitAsset('assets/js/' + f, read(path.join(SRC, 'scripts', f)))
const asset = rel => {
	if (!assetVersion[rel]) throw new Error('Unknown asset ' + rel)
	return rel + '?v=' + assetVersion[rel]
}

/* ---------------------------------------------------------------- chrome */
const CHEV = '<svg class="mega__chev" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="m6 9 6 6 6-6"/></svg>'
const groupOf = key => (menu.find(g => g.items.some(i => i.nav === key)) || {}).key

function header(pageKey) {
	const active = groupOf(pageKey)
	const out = [partial('topbar'), '<header class="header">', '<div class="scroll-progress-bar" id="scrollProgress"></div>', '<div class="container header-inner">',
		partial('brand'), '<nav class="nav mega" aria-label="Головне меню">']
	for (const g of menu) {
		out.push('<div class="mega__item" data-mega>')
		out.push(`<a href="${g.href}" class="nav__link mega__top${g.key === active ? ' active' : ''}" data-nav-group="${g.key}" aria-haspopup="true" aria-expanded="false" aria-controls="mega-${g.key}">${g.label}${CHEV}</a>`)
		out.push(`<div class="mega__panel" id="mega-${g.key}">`)
		out.push(`<div class="mega__intro"><strong>${g.label}</strong><p>${g.intro}</p><a class="mega__all" href="${g.href}">Відкрити розділ →</a></div>`)
		out.push('<ul class="mega__links">')
		for (const it of g.items) {
			// the section's own page is already the "Відкрити розділ →" link on the left: do not repeat it in the list
			if (it.href === g.href) continue
			const cur = it.nav === pageKey && !it.href.includes('#') ? ' aria-current="page"' : ''
			out.push(`<li><a href="${it.href}" data-nav="${it.nav}"${cur}><span>${it.label}</span><small>${it.desc}</small></a></li>`)
		}
		out.push('</ul></div></div>')
	}
	out.push('</nav>', partial('account-button'), partial('display-prefs'))
	out.push('<button class="burger" onclick="toggleMenu()" aria-label="Меню" aria-controls="mobileNav" aria-expanded="false"><span></span><span></span><span></span></button>')
	out.push('</div>', '</header>')
	out.push('<div class="mobile-nav" id="mobileNav"><a href="index.html" data-nav="home" class="mobile-nav__home">Головна</a>')
	for (const g of menu) {
		out.push(`<details class="mnav"${g.key === active ? ' open' : ''}><summary>${g.label}</summary><div class="mnav__links">`)
		const seen = new Set()
		for (const it of g.items) {
			if (seen.has(it.href)) continue
			seen.add(it.href)
			out.push(`<a href="${it.href}" data-nav="${it.nav}">${it.label}</a>`)
		}
		out.push('</div></details>')
	}
	out.push('</div>')
	return out.join('\n')
}

function footer() {
	const cols = menu.map(g => {
		const seen = new Set()
		const links = g.items.filter(it => !it.href.includes('#') && !seen.has(it.href) && seen.add(it.href)).map(it => `<a href="${it.href}">${it.label}</a>`)
		return `<div><h4>${g.label}</h4>${links.join('')}</div>`
	})
	return ['<footer class="footer">', partial('footer-brand'), '<div class="container footer-grid footer-grid--menu">', ...cols, '</div>',
		'<div class="container footer-bottom">© <span id="year"></span> · Студентська платформа · World Students</div>', '</footer>'].join('\n')
}

function head(fm) {
	const url = site.url + (fm.path === 'index.html' ? '' : fm.path)
	const img = site.url + fm.image
	const ld = [{
		'@context': 'https://schema.org', '@type': 'WebPage', name: fm.title, description: fm.description, url, inLanguage: 'uk',
		isPartOf: { '@type': 'WebSite', name: site.name, url: site.url },
		about: { '@type': 'CollegeOrUniversity', name: 'НТУ «Дніпровська політехніка»', url: 'https://nmu.org.ua/' },
	}]
	if (fm.breadcrumbs) ld.push({ '@context': 'https://schema.org', '@type': 'BreadcrumbList', itemListElement: fm.breadcrumbs.map(([name, p], i) => ({ '@type': 'ListItem', position: i + 1, name, item: site.url + (p === 'index.html' ? '' : p) })) })
	if (fm.jsonLdExtra) ld.push(...fm.jsonLdExtra)
	return ['<head>', '<meta charset="UTF-8">', '<meta name="viewport" content="width=device-width, initial-scale=1.0">',
		fm.googleVerification ? `<meta name="google-site-verification" content="${esc(fm.googleVerification)}">` : null,
		`<title>${esc(fm.title)}</title>`,
		`<meta name="description" content="${esc(fm.description)}">`,
		`<meta name="robots" content="${esc(fm.robots || 'index, follow, max-image-preview:large')}">`,
		`<link rel="canonical" href="${url}">`,
		`<meta name="theme-color" content="${site.themeColor}">`,
		`<meta property="og:type" content="${fm.ogType || 'website'}">`,
		`<meta property="og:site_name" content="${esc(site.name)}">`,
		'<meta property="og:locale" content="uk_UA">', '<meta property="og:locale:alternate" content="en_US">',
		`<meta property="og:title" content="${esc(fm.title)}">`,
		`<meta property="og:description" content="${esc(fm.description)}">`,
		`<meta property="og:url" content="${url}">`,
		`<meta property="og:image" content="${img}">`,
		'<meta name="twitter:card" content="summary_large_image">',
		`<meta name="twitter:title" content="${esc(fm.title)}">`,
		`<meta name="twitter:description" content="${esc(fm.description)}">`,
		`<meta name="twitter:image" content="${img}">`,
		'<link rel="preconnect" href="https://fonts.googleapis.com">', '<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>',
		`<link href="${site.fonts}" rel="stylesheet">`,
		'<link rel="icon" href="assets/img/favicon.svg" type="image/svg+xml">',
		'<link rel="icon" href="assets/img/favicon-32.png" sizes="32x32" type="image/png">',
		'<link rel="icon" href="assets/img/favicon-16.png" sizes="16x16" type="image/png">',
		'<link rel="apple-touch-icon" href="assets/img/favicon-180.png">',
		'<link rel="manifest" href="site.webmanifest">',
		// applies saved display preferences before the first paint (no flash of the wrong theme);
		// the preloader shows only on the first page of a visit (class no-pl hides it on the following pages)
		"<script>try{var d=document.documentElement,t=sessionStorage.getItem('ntu-theme')||'light';d.setAttribute('data-theme',t);d.lang=localStorage.getItem('ntu-lang')||'uk';var f=localStorage.getItem('ntu-fs');if(f)d.setAttribute('data-fs',f);if(localStorage.getItem('ntu-bw')==='1')d.setAttribute('data-bw','1');if(sessionStorage.getItem('ntu-pl')||(document.referrer&&new URL(document.referrer).host===location.host))d.classList.add('no-pl')}catch(e){}</script>",
		`<link rel="stylesheet" href="${asset('assets/css/style.css')}">`,
		`<script type="application/ld+json">${JSON.stringify(ld.length > 1 ? ld : ld[0]).replace(/</g, '\\u003c')}</script>`,
		'</head>'].filter(x => x !== null).join('\n')
}

/* ---------------------------------------------------------------- breadcrumbs */
// One depth everywhere: "Головна › <menu group> › <page>", or "Головна › <group>" on the group's own page.
// The group comes from menu.json (first group listing the page); the page name is the last crumb written in the page.
// Pages outside the menu (login, register...) keep their breadcrumbs as written.
const CRUMB_RE = /<(div|nav) class="breadcrumb"([^>]*)>([\s\S]*?)<\/\1>/
function unifyCrumbs(fm, file, body) {
	const g = menu.find(x => x.items.some(i => i.nav === fm.page && !i.href.includes('#')))
	const m = body.match(CRUMB_RE)
	if (!g || !m) return body
	const last = m[3].replace(/<[^>]*>/g, ' ').split('›').pop().replace(/\s+/g, ' ').trim()
	if (!last) return body
	const trail = [['Головна', 'index.html']]
	if (g.href !== file) trail.push([g.label, g.href])
	trail.push([last, file])
	fm.breadcrumbs = trail
	const attrs = m[2].replace(/\s*aria-label="[^"]*"/, '')
	const sep = '<span class="crumb-sep" aria-hidden="true">›</span>'
	const html = `<nav class="breadcrumb"${attrs} aria-label="Breadcrumb">` +
		trail.slice(0, -1).map(([n, h]) => `<a href="${h}">${n}</a>`).join(sep) + sep + `<span aria-current="page">${last}</span></nav>`
	return body.replace(CRUMB_RE, html)
}

/* ---------------------------------------------------------------- images */
// <img src="assets/img/x.jpg|png"> with an x.webp next to it (outside a <picture>) gets a WebP <source>.
// The <picture class="wp"> wrapper is display:contents, so the layout stays the same as with a bare <img>.
function webpPictures(body) {
	return body.replace(/<picture[\s\S]*?<\/picture>|<img\b[^>]*\ssrc="(assets\/img\/[^"?]+)\.(jpe?g|png)"[^>]*>/gi, (tag, base) => {
		if (!base || !fs.existsSync(path.join(ROOT, 'public', base + '.webp'))) return tag
		return `<picture class="wp"><source srcset="${base}.webp" type="image/webp">${tag}</picture>`
	})
}

/* ---------------------------------------------------------------- pages */
const FM_RE = /^<!--\s*(\{[\s\S]*?\})\s*-->\s*/
const pages = []
for (const f of listDir(path.join(SRC, 'pages'), '.html')) {
	const raw = read(path.join(SRC, 'pages', f))
	const m = raw.match(FM_RE)
	if (!m) throw new Error(f + ': missing front matter')
	let fm
	try { fm = JSON.parse(m[1]) } catch (e) { throw new Error(f + ': front matter is not valid JSON: ' + e.message) }
	for (const k of ['title', 'description', 'page']) if (!fm[k]) throw new Error(f + ': front matter needs "' + k + '"')
	fm.path = fm.path || f
	fm.image = fm.image || site.defaultImage
	const body = webpPictures(unifyCrumbs(fm, f, raw.slice(m[0].length).replace(/\s+$/, '')))
	const scripts = [...site.scripts, ...(fm.scripts || [])].map(s => `<script src="${asset('assets/js/' + s)}"></script>`)
	const html = ['<!DOCTYPE html>', '<html lang="uk">', head(fm), '', `<body data-page="${esc(fm.page)}">`,
		'<a class="skip-link" href="#main">Перейти до змісту</a>', partial('preloader'), header(fm.page), body, '', footer(), ...scripts, '</body>', '</html>', ''].join('\n')
	write(path.join(OUT, f), html)
	pages.push(fm)
}

/* ---------------------------------------------------------------- AI Student index */
// assets/data/ai-index.json: розділи кожної сторінки (заголовок + короткий текст) для пошуку AI Student,
// плюс база відповідей src/data/ai-kb.json. Генерується з джерел, тож завжди відповідає сайту.
{
	const strip = s => s.replace(/<(script|style|svg|iframe|noscript|template)[\s\S]*?<\/\1>/gi, ' ').replace(/<br\s*\/?>/gi, ' ')
		.replace(/<[^>]+>/g, ' ').replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&').replace(/&quot;/g, '"').replace(/&#x27;|&#39;/g, "'")
		.replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/\s+/g, ' ').trim()
	const groupLabel = key => (menu.find(g => g.items.some(i => i.nav === key)) || {}).label || ''
	const chunks = []
	for (const p of pages) {
		if (/noindex/.test(p.robots || '') && p.page !== 'account') continue
		const raw = read(path.join(SRC, 'pages', p.path === '' ? 'index.html' : p.path)).replace(FM_RE, '')
		const main = (raw.match(/<main[\s\S]*<\/main>/i) || [raw])[0]
		const parts = main.split(/(?=<h[23][\s>])/i)
		chunks.push({ u: p.path || 'index.html', t: p.title.replace(/\s+-\s+(World Students|НТУ «ДП»).*$/, ''), g: groupLabel(p.page), x: p.description })
		let lastId = ''
		for (const part of parts) {
			const hm = part.match(/^<h[23][^>]*>([\s\S]*?)<\/h[23]>/i)
			const ids = [...part.matchAll(/<section[^>]*\sid="([A-Za-z][\w-]*)"/g)]
			const hid = hm && (part.match(/^<h[23][^>]*\sid="([A-Za-z][\w-]*)"/) || [])[1]
			if (hm) {
				const h = strip(hm[1])
				const x = strip(part.slice(hm[0].length)).slice(0, 420)
				if (h && x.length > 30) chunks.push({ u: (p.path || 'index.html') + (hid || lastId ? '#' + (hid || lastId) : ''), t: h, p: p.title.replace(/\s+-\s+(World Students|НТУ «ДП»).*$/, ''), x })
			}
			if (ids.length) lastId = ids[ids.length - 1][1]
		}
	}
	const kb = JSON.parse(read(path.join(SRC, 'data/ai-kb.json')))
	emitAsset('assets/data/ai-index.json', JSON.stringify({ built: new Date().toISOString().slice(0, 10), kb: kb.entries, pages: chunks }))
}

/* ---------------------------------------------------------------- sitemap */
const today = new Date().toISOString().slice(0, 10)
const indexable = pages.filter(p => !/noindex/.test(p.robots || '')).sort((a, b) => (a.path === 'index.html' ? -1 : b.path === 'index.html' ? 1 : a.path.localeCompare(b.path)))
write(path.join(OUT, 'sitemap.xml'), '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' +
	indexable.map(p => {
		const sm = Object.assign({ changefreq: 'monthly', priority: '0.7' }, p.sitemap)
		return `<url><loc>${site.url}${p.path === 'index.html' ? '' : p.path}</loc><lastmod>${today}</lastmod><changefreq>${sm.changefreq}</changefreq><priority>${sm.priority}</priority></url>`
	}).join('\n') +
	'\n</urlset>\n')

console.log(`Built ${pages.length} pages (${indexable.length} in sitemap) -> ${path.relative(ROOT, OUT) || '.'}`)
